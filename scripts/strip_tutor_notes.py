"""Keep the tutor notes off the published site.

Every lesson ends with a `## Tutor notes` section. It stays in the lesson file,
because the authoring agents write it there and lint_lesson.py checks for it,
but students read the site, so the section is cut from each page as it is
built. The notes are collected into tutor/lesson-notes.md instead, which is
never published.

This is a MkDocs hook (see `hooks:` in mkdocs.yml). It can also be run on its
own to refresh the collected notes:

    python scripts/strip_tutor_notes.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
OUT = ROOT / "tutor" / "lesson-notes.md"

# The section runs from its heading to the end of the page - it is always last.
TUTOR = re.compile(r"^## Tutor notes[ \t]*$", re.MULTILINE)
TITLE = re.compile(r"^# (.+)$", re.MULTILINE)


def split(markdown: str) -> tuple[str, str]:
    """Return (page without tutor notes, the tutor notes or '')."""
    m = TUTOR.search(markdown)
    if not m:
        return markdown, ""
    return markdown[:m.start()].rstrip() + "\n", markdown[m.end():].strip()


def lesson_key(path: Path) -> list[int]:
    # "1-10-some-slug.md" sorts after "1-9-..." rather than after "1-1-..."
    return [int(n) for n in re.findall(r"^\d+|(?<=-)\d+(?=-)", path.stem)[:2]]


def collect() -> int:
    parts = ["# Tutor notes - all lessons",
             "",
             "Generated by `scripts/strip_tutor_notes.py` on every build; edit "
             "the `## Tutor notes` section of the lesson instead. These notes "
             "are cut from the published site."]
    count = 0
    lessons = [p for p in DOCS.rglob("*.md") if "worksheets" not in p.parts]
    for path in sorted(lessons, key=lambda p: (p.parent.name, lesson_key(p))):
        text = path.read_text(encoding="utf-8")
        _, notes = split(text)
        if not notes:
            continue
        title = TITLE.search(text)
        parts += ["", f"## {title.group(1) if title else path.stem}", "",
                  f"*Source: `{path.relative_to(ROOT).as_posix()}`*", "", notes]
        count += 1
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    return count


def on_pre_build(config, **kwargs):
    collect()


def on_page_markdown(markdown, page, config, files, **kwargs):
    return split(markdown)[0]


if __name__ == "__main__":
    print(f"tutor notes: {collect()} lesson(s) -> {OUT.relative_to(ROOT)}")
